function getLiturgicalSeason() {
    const now = new Date();
    const year = now.getFullYear();
    const month = now.getMonth() + 1;
    const day = now.getDate();

    if ((month === 11 && day >= 27) || (month === 12 && day <= 24)) {
        return { season: 'advent', name: 'Advent' };
    }
    if ((month === 12 && day >= 25) || (month === 1 && day <= 13)) {
        return { season: 'christmas', name: 'Christmas' };
    }
    if ((month === 2 && day >= 15) || (month === 3) || (month === 4 && day <= 15)) {
        return { season: 'lent', name: 'Lent' };
    }
    if ((month === 4 && day >= 16) || (month === 5)) {
        return { season: 'easter', name: 'Easter' };
    }
    if ((month === 8 && day === 15) || (month === 12 && day === 8) || (month === 1 && day === 1)) {
        return { season: 'feast', name: 'Feast Day' };
    }
    return { season: 'ordinary', name: 'Ordinary Time' };
}

function getGreeting() {
    const hour = new Date().getHours();
    if (hour < 12) return "Good morning";
    if (hour < 18) return "Good afternoon";
    return "Good evening";
}

function getTodaysMystery() {
    const day = new Date().getDay();
    const mysteryMap = {
        0: 'glorious',
        1: 'joyful',
        2: 'sorrowful',
        3: 'glorious',
        4: 'luminous',
        5: 'sorrowful',
        6: 'joyful'
    };
    return mysteries[mysteryMap[day]];
}

function init() {
    const mystery = getTodaysMystery();
    const liturgical = getLiturgicalSeason();
    
    document.body.className = liturgical.season;
    document.getElementById('greeting').textContent = `${getGreeting()}, today we pray`;
    document.getElementById('mysteryName').textContent = mystery.name;
    document.getElementById('seasonIndicator').textContent = liturgical.name;
}

function showPrayers() {
    const mystery = getTodaysMystery();
    document.getElementById('prayerTitle').textContent = mystery.name;
    
    let mysteriesHTML = '';
    mystery.decades.forEach((decade, index) => {
        mysteriesHTML += `
            <div class="mystery-meditation">
                <h4>${decade.title}</h4>
                <p>${decade.meditation}</p>
            </div>
            <div class="prayer-section">
                <p><strong>Our Father</strong> — Pray one Our Father</p>
                <p><strong>Hail Mary</strong> — Pray ten Hail Marys while meditating on the mystery</p>
                <p><strong>Glory Be</strong> — Pray one Glory Be</p>
                <p class="instruction">O my Jesus, forgive us our sins, save us from the fires of hell, and lead all souls to heaven, especially those in most need of thy mercy.</p>
            </div>
        `;
    });
    
    document.getElementById('mysteriesContent').innerHTML = mysteriesHTML;
    document.getElementById('homePage').style.display = 'none';
    document.getElementById('prayerPage').style.display = 'block';
    window.scrollTo(0, 0);
}

function showHome() {
    document.getElementById('homePage').style.display = 'block';
    document.getElementById('prayerPage').style.display = 'none';
    window.scrollTo(0, 0);
}

init();